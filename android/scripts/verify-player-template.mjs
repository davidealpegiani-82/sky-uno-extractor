import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const template = readFileSync('android/app/src/main/assets/player-template.html', 'utf8');
const kotlin = readFileSync('android/app/src/main/java/it/davidealpegiani/skyunoextractor/MainActivity.kt', 'utf8');
const lite = readFileSync('android/playerlite/src/main/java/it/davidealpegiani/skylite/MainActivity.kt', 'utf8');
const web = readFileSync('index.html', 'utf8');
assert.equal((template.match(/__CHANNELS__/g) || []).length, 1, 'template must contain exactly one channel placeholder');
assert.match(template, /hls\.js@1\.7\.4\/dist\/hls\.min\.js/, 'HLS.js must be pinned');
assert.match(template, /liveSyncDurationCount:8/);
assert.match(template, /liveMaxLatencyDurationCount:24/);
assert.match(template, /maxBufferLength:90/);
assert.match(template, /maxMaxBufferLength:90/);
assert.match(template, /START_BUFFER_SECONDS=6/);
assert.match(template, /MIN_BUFFER_SECONDS=30/);
assert.match(template, /TARGET_BUFFER_SECONDS=90/);
assert.doesNotMatch(template, /RESUME_BUFFER_SECONDS|PAUSE_BUFFER_SECONDS|bufferGuard|video\\.pause\\(\\).*buffer/i, 'HTML playback must not use the old 6/15-second pause loop');
assert.ok(template.includes('function beginPrebuffer()'), 'startup prebuffer must be implemented');
assert.ok(template.includes('function keepBufferLoading()'), 'low-buffer recovery must keep HLS loading');
assert.match(template, /maxBufferLength:90/);
assert.match(template, /maxMaxBufferLength:90/);
assert.match(template, /fullscreenBtn/);
assert.match(template, /videoStage\\.requestFullscreen/);
assert.match(template, /scheme=skylite;package=it\.davidealpegiani\.skylite/);
assert.match(template, /Sky-Player-Lite\.apk/);
assert.doesNotMatch(template, /cast_sender|cast\.framework|castBtn|Google Cast|Trasmetti/i, 'exported player must not contain Cast');
assert.match(kotlin, /setBufferDurationsMs\(\s*30_000,[\s\S]*?90_000,[\s\S]*?6_000,[\s\S]*?15_000[\s\S]*?\)/);
assert.match(kotlin, /setBufferDurationsMs\(\s*30_000,[\s\S]*?90_000,[\s\S]*?6_000,[\s\S]*?15_000[\s\S]*?\)/);
assert.match(lite, /setBufferDurationsMs\(\s*30_000,\s*90_000,\s*6_000,\s*15_000/s, 'Player Lite must use the same load-control profile as Extractor');
assert.match(lite, /setPrioritizeTimeOverSizeThresholds\(true\)/);
assert.match(lite, /setTargetLiveOffsetIncrementOnRebufferMs\(10_000\)/);
assert.match(lite, /setMinPlaybackSpeed\(0\.97f\)/);
assert.match(lite, /setMaxPlaybackSpeed\(1\.03f\)/);
assert.match(lite, /DefaultLoadErrorHandlingPolicy\(6\)/);
assert.match(web, /android\/app\/src\/main\/assets\/player-template\.html/, 'web exporter must use the same template');
assert.match(web, /async function playerHtml\(/);
console.log('Player template checks passed.');
